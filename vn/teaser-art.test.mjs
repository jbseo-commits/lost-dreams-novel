function webpDimensions(buffer) {
  assert.equal(buffer.toString('ascii', 0, 4), 'RIFF');
  assert.equal(buffer.toString('ascii', 8, 12), 'WEBP');
  for (let offset = 12; offset + 8 <= buffer.length;) {
    const type = buffer.toString('ascii', offset, offset + 4);
    const length = buffer.readUInt32LE(offset + 4);
    const start = offset + 8;
    if (type === 'VP8X' && length >= 10) {
      return { width: 1 + buffer.readUIntLE(start + 4, 3), height: 1 + buffer.readUIntLE(start + 7, 3) };
    }
    if (type === 'VP8L' && length >= 5 && buffer[start] === 0x2f) {
      return {
        width: 1 + buffer[start + 1] + ((buffer[start + 2] & 0x3f) << 8),
        height: 1 + ((buffer[start + 2] >> 6) | (buffer[start + 3] << 2) | ((buffer[start + 4] & 0x0f) << 10)),
      };
    }
    if (type === 'VP8 ' && length >= 10 && buffer[start + 3] === 0x9d && buffer[start + 4] === 0x01 && buffer[start + 5] === 0x2a) {
      return { width: buffer.readUInt16LE(start + 6) & 0x3fff, height: buffer.readUInt16LE(start + 8) & 0x3fff };
    }
    offset = start + length + (length & 1);
  }
  assert.fail('WebP dimensions were not found');
}

test('27 runtime sprites and 16 cutscenes resolve to the packaged art including corrected parents', async () => {
  assert.equal(spriteKeys.length, 27);
  assert.equal(cgKeys.length, 16);
  assert.equal(teaserKeys.length, 43);
  assert.equal(new Set(teaserKeys).size, 43);
  for (const key of teaserKeys) {
    assert.equal(EP1_ASSETS[key], PARENT_ASSETS[key]??`assets/teaser-style/${kebab(key)}.webp`, key);
    const bytes = await readFile(source(EP1_ASSETS[key]));
    assert.ok((await stat(source(EP1_ASSETS[key]))).size > 0, key);
    const { width, height } = webpDimensions(bytes);
    if (spriteKeys.includes(key)) {
      assert.ok(width >= 1024 && height >= 1536, `${key}: native portrait resolution`);
      assert.equal(bytes.toString('ascii', 12, 16), 'VP8X', `${key}: extended alpha format`);
      assert.ok(bytes[20] & 0x10, `${key}: actual alpha channel`);
    } else assert.ok(width >= 1536 && height >= 900, `${key}: event CG resolution`);
    if (key === 'dreamBeach') {
      assert.deepEqual({ width, height }, { width: 1536, height: 1024 });
      assert.ok(bytes.includes(Buffer.from('VP8L')), 'beach uses lossless pixels');
      assert.ok(bytes.length > 100000, 'reject the former tiny compressed thumbnail');
    }
  }
  assert.equal(EP1_ASSETS.seoinNight, 'assets/ep1/seoin-night.webp');
});

test('teaser provenance records match generated bytes, dimensions, and untouched source images', async () => {
  const manifest = JSON.parse(await readFile(source('assets/teaser-style/provenance.json'), 'utf8'));
  assert.equal(manifest.tool, 'built-in image_gen');
  assert.equal(manifest.exactModel, 'not exposed');
  assert.ok(manifest.styleReference?.file);
  assert.equal(manifest.assets.length, 43);
  const byKey = new Map(manifest.assets.map(item => [item.key, item]));
  assert.equal(byKey.size, 43);
  for (const key of teaserKeys) {
    const item = byKey.get(key);
    assert.ok(item, key);
    assert.equal(item.file, `${kebab(key)}.webp`, key);
    assert.equal(item.kind, spriteKeys.includes(key) ? 'sprite' : 'event-cg', key);
    assert.ok(/^[a-f\d]{64}$/i.test(item.sha256), `${key}: generated hash`);
    assert.ok(/^[a-f\d]{64}$/i.test(item.sourceSha256), `${key}: source hash`);
    assert.ok(Array.isArray(item.dimensions) && item.dimensions.length === 2, `${key}: dimensions`);
    assert.equal(typeof item.transparent, 'boolean', `${key}: transparency`);
    assert.match(item.original, /^vn\/assets\//, `${key}: original path`);
    const generated = await readFile(source(`assets/teaser-style/${item.file}`));
    assert.equal(item.bytes, generated.length, `${key}: generated byte count`);
    assert.equal(createHash('sha256').update(generated).digest('hex'), item.sha256, `${key}: generated hash`);
    assert.deepEqual(webpDimensions(generated), { width: item.dimensions[0], height: item.dimensions[1] }, `${key}: generated dimensions`);
    const original = await readFile(source(item.original.replace(/^vn\//, '')));
    assert.equal(createHash('sha256').update(original).digest('hex'), item.sourceSha256, `${key}: original image was preserved`);
  }
});

test('every authored parent pose in the public demo and the father close-up use the corrected art', async () => {
  const box={window:{}};vm.runInNewContext(await readFile(source('story-data.js'),'utf8'),box);
  const story=publicDemoStory(normalizeStory(box.window.STORY)),seen=new Set();
  for(const chapter of story.chapters)for(let i=0;i<chapter.beats.length;i++){
    const cue=chapter.id==='1'?episodeOneDirection(chapter,i):chapter.id==='2'?episodeTwoDirection(chapter,i):coreSceneDirection(chapter,i);
    for(const actor of cue?.actors??[])if(['mother','father'].includes(actor.id)){
      assert.ok(PARENT_ASSETS[actor.asset],`${chapter.id}:${i} ${actor.asset}`);
      assert.equal(EP1_ASSETS[actor.asset],PARENT_ASSETS[actor.asset]);seen.add(actor.id);
    }
  }
  assert.deepEqual([...seen].sort(),['father','mother']);
  assert.ok(EPISODE_CUTSCENES.some(c=>c.chapter==='2'&&c.cg==='medicalTablet'));
  assert.equal(EP1_ASSETS.medicalTablet,PARENT_ASSETS.medicalTablet);
  const manifest=JSON.parse(await readFile(source('assets/parent-style/provenance.json'),'utf8'));
  assert.equal(manifest.assets.length,10);
  for(const item of manifest.assets){
    const bytes=await readFile(source(item.file));
    assert.equal(createHash('sha256').update(bytes).digest('hex'),item.sha256);
    assert.equal(EP1_ASSETS[item.key],item.file);
    const original=await readFile(source(item.original));
    assert.equal(createHash('sha256').update(original).digest('hex'),item.sourceSha256);
  }
});

